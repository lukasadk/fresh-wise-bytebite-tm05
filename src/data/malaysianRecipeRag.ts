const recipeImageBaseUrl = (
  process.env.EXPO_PUBLIC_GROCERY_AI_API_URL
  ?? process.env.EXPO_PUBLIC_WASTEWISE_BROWSER_MODEL_API_URL
  ?? API_BASE_URL
).trim().replace(/\/+$/, '');

function hostedRecipeImage(path: string): string {
  return path.startsWith('/') ? `${recipeImageBaseUrl}${path}` : path;
}

function imageForRecipe(hint: MalaysianRecipeHint): string {
  const title = normalise(hint.title);
  const text = normalise([hint.title, ...hint.ingredients].join(' '));
  let image: string;
  if (/noodle|mee|bee hoon|vermicelli|laksa|ramen/.test(text)) image = RECIPE_IMAGES.noodles;
  else if (/bread|roti|toast|sandwich/.test(title)) image = RECIPE_IMAGES.bread;
  else if (/curry|kari|masak lemak|santan|coconut milk/.test(text)) image = RECIPE_IMAGES.curry;
  else if (/fish|ikan|sardine|salmon|prawn|shrimp/.test(text)) image = RECIPE_IMAGES.fish;
  else if (/soup|sup|porridge|bubur/.test(text)) image = RECIPE_IMAGES.soup;
  else if (/bread|roti|toast|sandwich/.test(text)) image = RECIPE_IMAGES.bread;
  else if (
    /fruit|banana|apple|mango|orange|blueberry|watermelon/.test(title)
    && !/rice|noodle|chicken|fish|beef|curry|soup/.test(title)
  ) image = RECIPE_IMAGES.fruit;
  else if (
    /milk|yogurt|yoghurt|dairy/.test(title)
    && !/rice|noodle|chicken|fish|beef|curry|soup/.test(title)
  ) image = RECIPE_IMAGES.milk;
  else if (/vegetable|kangkung|choy sum|spinach|sawi|salad|kerabu/.test(text)) image = RECIPE_IMAGES.vegetable;
  else if (/egg|telur|omelette/.test(text)) image = RECIPE_IMAGES.egg;
  else image = RECIPE_IMAGES.rice;
  return hostedRecipeImage(image);
}

function quantityForIngredient(ingredient: string): string {
  const value = normalise(ingredient);
  if (/rice/.test(value)) return `2 cups ${ingredient}`;
  if (/noodle|mee|vermicelli|pasta/.test(value)) return `250 g ${ingredient}`;
  if (/egg|telur/.test(value)) return '2 eggs';
  if (/chicken|fish|prawn|shrimp|tofu|tauhu|beef/.test(value)) return `250 g ${ingredient}`;
  if (/soy sauce|oyster sauce|chilli sauce|sambal|mayonnaise|sesame paste/.test(value)) return `1 tbsp ${ingredient}`;
  if (/garlic/.test(value)) return '2 garlic cloves';
  if (/onion|shallot/.test(value)) return `1 medium ${ingredient}`;
  if (/coconut milk|stock/.test(value)) return `200 ml ${ingredient}`;
  if (/curry powder|turmeric|belacan|shrimp paste/.test(value)) return `1 tsp ${ingredient}`;
  return `1 cup ${ingredient}`;
}

function detailedSteps(hint: MalaysianRecipeHint): string[] {
  if (hint.steps.length >= 5) return hint.steps;
  const ingredients = hint.ingredients.slice(0, 5).join(', ');
  const main = hint.ingredients[0] || 'main ingredient';
  const original = hint.steps.map((step, index) => {
    const timing = index === 0 ? '2 to 3 minutes' : index === 1 ? '3 to 5 minutes' : '1 to 2 minutes';
    return `${step.replace(/\.$/, '')}; cook for ${timing}, stirring regularly and keeping the heat at medium unless stated otherwise.`;
  });
  return [
    `Measure the ingredients for two servings (${ingredients}) and cut solid ingredients into even bite-sized pieces before heating the pan.`,
    'Heat 1 tablespoon cooking oil in a wok or saucepan over medium-high heat for 45 seconds.',
    ...original,
    `Check that ${main} is fully cooked and tender; poultry must reach 75 C and fish should flake easily at the thickest point.`,
    'Remove from the heat, rest for 1 minute, and serve immediately while hot.',
  ].slice(0, 8);
}

function enrichRecipeHint(hint: MalaysianRecipeHint): MalaysianRecipeHint {
  return {
    ...hint,
    ingredientQuantities: hint.ingredientQuantities ?? hint.ingredients.map(quantityForIngredient),
    steps: detailedSteps(hint),
    imageUrl: hint.imageUrl ?? imageForRecipe(hint),
    imageAlt: hint.imageAlt ?? `Serving suggestion for ${hint.title}`,
    prepMinutes: hint.prepMinutes ?? 10,
    cookMinutes: hint.cookMinutes ?? 15,
  };
}

function itemText(item: FoodItem): string {
  return normalise([item.name, item.canonical_food_name, item.category, item.unit].filter(Boolean).join(' '));
}

function matchesSignal(text: string, signal: string): boolean {
  const normalisedSignal = normalise(signal);
  return !!normalisedSignal && text.includes(normalisedSignal);
}

export function selectMalaysianRecipeHints(inventory: FoodItem[], limit = 8): MalaysianRecipeHint[] {
  const inventoryTexts = inventory.map(itemText).filter(Boolean);
  const expiringTexts = inventory
    .filter((item) => item.days_to_expiry !== null && item.days_to_expiry <= 3)
    .map(itemText)
    .filter(Boolean);

  const ranked = RECIPE_HINTS
    .map((hint) => {
      const signalHits = hint.pantrySignals.filter((signal) =>
        inventoryTexts.some((text) => matchesSignal(text, signal)),
      ).length;
      const expiringHits = hint.pantrySignals.filter((signal) =>
        expiringTexts.some((text) => matchesSignal(text, signal)),
      ).length;
      return { hint, score: signalHits * 2 + expiringHits * 3 };
    })
    .filter(({ score }) => score > 0)
    .sort((a, b) => b.score - a.score || a.hint.title.localeCompare(b.hint.title))
    .slice(0, limit)
    .map(({ hint }) => hint);

  if (ranked.length >= limit) return ranked.map(enrichRecipeHint);

  const usedTitles = new Set(ranked.map((hint) => hint.title));
  const fallback = RECIPE_HINTS
    .filter((hint) => !usedTitles.has(hint.title))
    .slice(0, Math.max(0, limit - ranked.length));
  return [...ranked, ...fallback].map(enrichRecipeHint);
}
